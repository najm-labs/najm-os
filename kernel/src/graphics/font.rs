//! A 5x7 bitmap font.
//!
//! The smallest thing that can put readable words on a screen, and
//! deliberately so. The alternatives were both worse for a kernel:
//!
//! - **A scalable font renderer.** Parsing TrueType means running a
//!   bytecode interpreter over untrusted input, in the kernel, to draw a
//!   label. ARCHITECTURE.md section 2d, threat 6 lists font parsing by a
//!   privileged process as a classic remote-code-execution vector and
//!   requires it to happen in a sandboxed subprocess with a minimal
//!   capability set. A kernel-side TrueType parser would be that exact
//!   threat, introduced by the code meant to respect it.
//! - **A large embedded bitmap font.** A full 8x16 ASCII font is around
//!   1.5 KiB of glyph data authored by hand or generated by a tool that
//!   then has to be trusted. At 5x7 the whole table is under 500 bytes
//!   and every glyph can be read and checked by eye in the source.
//!
//! ## Layout
//!
//! Each glyph is five bytes, one per **column**, with the low seven bits
//! of each byte giving the pixels top to bottom. Column-major rather than
//! row-major because that is how the classic 5x7 LED-matrix fonts this is
//! modelled on are laid out, and because it makes each glyph's shape
//! legible in the source: read the five hex bytes as five vertical
//! slices.
//!
//! Coverage is ASCII 0x20-0x7E. Anything outside that renders as a filled
//! box, which is a visible, unmistakable "this character is not
//! supported" rather than a blank space that reads as intentional.

/// Glyph width in pixels, excluding inter-character spacing.
pub const GLYPH_WIDTH: usize = 5;
/// Glyph height in pixels.
pub const GLYPH_HEIGHT: usize = 7;
/// Horizontal advance per character, i.e. glyph width plus one column of
/// spacing. Without the spacing, adjacent letters touch and words become
/// unreadable at this size.
pub const ADVANCE: usize = GLYPH_WIDTH + 1;

/// The replacement glyph: a filled box, for any character outside the
/// supported range.
const UNKNOWN: [u8; 5] = [0x7F, 0x7F, 0x7F, 0x7F, 0x7F];

